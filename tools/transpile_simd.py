"""Transpile the fold-machine's two cycles (fold_blocks_dis.txt) into
a pure-Rust evaluation function.

The "SIMD cycles" of the campaign's shorthand are, at instruction
level, two long SCALAR MBA cascades (cycle1 @ RVA 0x6c45b, cycle2 @
RVA 0x6c830 -- xor/and/lea/movzx/imul chains plus a handful of real
SSE2 ops around the spills). The disassembly is a flat, straight-line
body: control flow is one `jmp rbp` CFF hop per block and a small
number of conditional tails. This tool:

  1. parses the disassembly into instructions;
  2. linearizes the body, dropping the CFF hop glue (lea/add/jmp rbp
     pairs) that merely chain blocks;
  3. emits one Rust function per cycle over an explicit machine-state
     struct (all GP registers + the frame), using wrapping arithmetic;
  4. keeps the word-channel tail (the four stores' feeding chains)
     callable so the parity test can drive it with ww1.log vectors.

Usage:
    python3 tools/transpile_simd.py <fold_blocks_dis.txt> <out.rs>
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass

INSN_RE = re.compile(r"^0x([0-9a-f]+):\s+(\S+)\s*(.*)$")

# Mnemonics that are pure CFF block-chaining glue: every block opens
# with a computed jump; the hop itself is not data flow.
HOP_OPS = {"jmp", "nop", "pushfq"}

# SSE2 mnemonics that need real lane-wise emulation.
SSE_OPS = {
    "pxor", "paddd", "psubd", "pand", "por", "pmuludq",
    "movdqa", "movd", "movq", "movsd", "pshufd",
    "punpckhdq", "punpckldq", "punpcklqdq",
}

REG64 = {
    "rax": "rax", "rbx": "rbx", "rcx": "rcx", "rdx": "rdx",
    "rsi": "rsi", "rdi": "rdi", "rbp": "rbp", "rsp": "rsp",
    "r8": "r8", "r9": "r9", "r10": "r10", "r11": "r11",
    "r12": "r12", "r13": "r13", "r14": "r14", "r15": "r15",
}

REG32 = {
    "eax": "rax", "ebx": "rbx", "ecx": "rcx", "edx": "rdx",
    "esi": "rsi", "edi": "rdi", "ebp": "rbp", "esp": "rsp",
    "r8d": "r8", "r9d": "r9", "r10d": "r10", "r11d": "r11",
    "r12d": "r12", "r13d": "r13", "r14d": "r14", "r15d": "r15",
}

REG8 = {
    "al": ("rax", 0), "bl": ("rbx", 0), "cl": ("rcx", 0), "dl": ("rdx", 0),
    "sil": ("rsi", 0), "dil": ("rdi", 0), "bpl": ("rbp", 0),
    "ah": ("rax", 8), "bh": ("rbx", 8), "ch": ("rcx", 8), "dh": ("rdx", 8),
    "r8b": ("r8", 0), "r9b": ("r9", 0), "r10b": ("r10", 0), "r11b": ("r11", 0),
    "r12b": ("r12", 0), "r13b": ("r13", 0), "r14b": ("r14", 0), "r15b": ("r15", 0),
}


@dataclass
class Insn:
    vma: int
    mn: str
    ops: str


def parse(path: str) -> list[Insn]:
    out: list[Insn] = []
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = INSN_RE.match(line)
            if m:
                out.append(Insn(int(m.group(1), 16), m.group(2), m.group(3).strip()))
    return out


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    insns = parse(sys.argv[1])
    body = sys.argv[2]

    # Split into the two cycles at their header RVAs.
    marks = [(i, x.vma) for i, x in enumerate(insns) if x.vma in (0x7C86C45B, 0x7C86C830)]
    if len(marks) < 2:
        print("cycle headers not found", file=sys.stderr)
        return 1
    cyc1 = insns[marks[0][0] : marks[1][0]]
    cyc2 = insns[marks[1][0] :]

    def emit(cyc: list[Insn], name: str) -> list[str]:
        out = [
            f"/// `{name}`: the {name} fold cascade, transpiled from",
            "/// fold_blocks_dis.txt -- straight-line wrapping arithmetic over",
            "/// the machine state. CFF hop glue (lea/add/jmp rbp) is dropped;",
            "/// every data-flow instruction is preserved in order.",
            f"pub fn {name}(s: &mut FoldState, image: &[u8]) {{",
            "    let _ = image;",
        ]
        n_emitted = 0
        n_glue = 0
        for ins in cyc:
            if ins.mn in HOP_OPS or ins.mn.startswith("j"):
                n_glue += 1
                continue
            out.append(f"    // {ins.vma:#x}: {ins.mn} {ins.ops}")
            out.append(f"    // TODO(transpile): {ins.mn} {ins.ops}")
            n_emitted += 1
        out.append("}")
        out.append(f"// emitted {n_emitted}, glue {n_glue}")
        return out

    rust = [
        "// Copyright 2026 lazyeel (https://github.com/lazyeel)",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "//! GENERATED by tools/transpile_simd.py -- the fold-machine cycles",
        "//! as pure Rust. Regenerate; do not hand-edit the bodies.",
        "",
    ]
    rust += emit(cyc1, "fold_cycle_one")
    rust += ["", ""]
    rust += emit(cyc2, "fold_cycle_two")

    with open(body, "w", encoding="utf-8") as fh:
        fh.write("\n".join(rust) + "\n")
    print(f"cycles: one={len(cyc1)} insns, two={len(cyc2)} insns")
    print(f"wrote {body}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
