def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--core", required=True)
    ap.add_argument("--check-core", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--state-dir", required=True)
    args = ap.parse_args()
    lab, stream, state = capture(args.core)
    check_lab, check_stream, check_state = capture(args.check_core)
    assert [pc for pc, _ in stream] == [pc for pc, _ in check_stream]
    for rva in PAGE_RVAS:
        assert bytes(lab.uc.mem_read(LIB_BASE + rva, 0x1000)) == bytes(
            check_lab.uc.mem_read(LIB_BASE + rva, 0x1000))

    md = Cs(CS_ARCH_X86, CS_MODE_64)
    md.detail = True
    insns = []
    for address, size in stream:
        ins = next(md.disasm(bytes(lab.uc.mem_read(address, size)), address))
        if ins.mnemonic in ("call", "ret") or (ins.mnemonic.startswith("j") and ins.mnemonic != "jmp"):
            raise ValueError("unsupported mixer control flow at %#x" % address)
        insns.append(ins)
    audit_flags(insns)
    for ins in insns:
        emit_mixer(ins)

    out_dir = Path(args.out_dir)
    (out_dir / "mixer_tables.rs").write_text(tables_rust(lab))
    (out_dir / "mixer_core.rs").write_text(TEMPLATE.replace("{{BODY}}", render_body(insns)))
    state_dir = Path(args.state_dir)
    state_dir.mkdir(parents=True, exist_ok=True)
    os.chmod(state_dir, 0o700)
    for name, blob in [("sequential.bin", state), ("a5.bin", check_state)]:
        path = state_dir / name
        path.write_bytes(blob)
        os.chmod(path, 0o600)
    print("transpiled", len(insns), "instructions and", len(PAGE_RVAS), "data pages")


if __name__ == "__main__":
    main()
