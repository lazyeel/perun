//! The early-series driver: the cfg cascade's 368-byte packet
//! generator, wrapping the transcribed body (early_zone.rs).
//!
//! The measured anatomy (2026-10-24b/c):
//!
//! * the cascade's linear body runs 0x67015..0x67891 (the
//!   SPIM ingress at 0x6763e, the planter-row image reads,
//!   the MBA mixers) and ends with ONE byte store
//!   `mov [rax+r9], dl` -- the write the ww logs caught 368
//!   times with r9 = 0..0x16f;
//! * each iteration then hops through the cursor table
//!   (0x67a70..0x67a94: inc r14d; the cursor-table fetch;
//!   jmp rdx) back into the body's head, which re-seeds the
//!   working registers from rdi (`xor r9,0xd2`,
//!   `lea eax,[rdi-0x5a0]`, the planter-row loads);
//! * the SPIM enters through the packet (the read at 0x6763e,
//!   the masked offset 0x45a3f7f) -- the delta battery proved
//!   the output is a direct function of the SPIM bytes.
//!
//! The HONEST BOUNDARY of this module: the body is transcribed
//! instruction-for-instruction (compiling, clippy-clean), but
//! a full independent run additionally needs (a) the
//! iteration-0 entry state -- the prologue's tape, which the
//! live session seeds and the int3 probes cannot reach (the
//! hop chain breaks under them), and (b) the runtime-built
//! cursor/planter pages. This driver therefore takes the
//! entry state as an explicit parameter: the white-box
//! contract is "entry state + SPIM -> 368 generated bytes",
//! and every caller supplies its own provenance.

use crate::early_zone::{fold_zone_body, FoldState, FoldView};

/// The early-series run result: the 368 generated bytes plus
/// the final state (the tape the next round consumes).
#[derive(Debug, Clone)]
pub struct EarlySeriesOutput {
    pub bytes: [u8; 368],
    pub final_state: FoldState,
}

/// Run the early series over an entry state.
///
/// The entry state is the prologue's product: its registers
/// carry the session tape (rdi/r9 seeds the head consumes) and
/// the frame carries the table slots. The image view answers
/// the guest's byte/dword/qword reads (the SPIM travels in
/// the packet -- the view's packet mapping is the caller's).
#[must_use = "the generation is pure; use the output"]
pub fn run(entry: FoldState, view: &dyn FoldView) -> EarlySeriesOutput {
    let mut s = entry;
    let mut out = [0u8; 368];
    for r9 in 0..368u64 {
        s.r9 = r9;
        fold_zone_body(&mut s, view);
        // The body's store lands at [rax+r9]; the transcribed
        // body writes through the view's packet mapping -- the
        // driver collects the byte the state's own rax/r9 pin.
        // (The generator's packet slot carries the SPIM at
        // +0x10.. and the generated byte lands at +4+r9.)
        out[r9 as usize] = (s.rdx & 0xff) as u8;
    }
    EarlySeriesOutput {
        bytes: out,
        final_state: s,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct ZeroView;
    impl FoldView for ZeroView {
        fn byte_at(&self, _addr: u64) -> u8 {
            0
        }
        fn dword_at(&self, _addr: u64) -> u32 {
            0
        }
        fn qword_at(&self, _addr: u64) -> u64 {
            0
        }
    }

    /// The driver runs 368 iterations over a zero entry and
    /// returns a full buffer -- the loop contract, the body's
    /// mechanics, and the state plumbing all hold.
    #[test]
    fn driver_runs_368_iterations() {
        let out = run(FoldState::default(), &ZeroView);
        assert_eq!(out.bytes.len(), 368);
        // A zero view and a zero entry produce a deterministic
        // tape: the first bytes are the head's own algebra.
        // (The exact values are the body's product -- pinned
        // by the guest parity once the entry state is live.)
        let nz = out.bytes.iter().filter(|b| **b != 0).count();
        assert!(nz > 0, "the transcribed body must produce bytes");
    }
}
